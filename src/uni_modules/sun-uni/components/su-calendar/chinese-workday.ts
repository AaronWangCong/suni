/**
 * 判断给定的日期是否为工作日。
 * 
 * @param {string | number | Date} day - 要判断的日期，可以是日期字符串、时间戳或 Date 对象。
 * @returns {boolean} 如果是工作日返回 true，否则返回 false。
 */
function isWorkday(day: string | number | Date) {
  // 调用 formatDate 函数格式化输入的日期
  const fd = formatDate(day);
  // 检查该日期是否在调休工作日列表中
  if (WEEKENDS_WORKDAY[fd.date]) {
    // 如果在列表中，说明该日期是调休工作日，返回 true
    return true;
  }
  // 检查该日期是否在节假日列表中
  else if (HOLIDAYS[fd.date]) {
    // 如果在列表中，说明该日期是节假日，返回 false
    return false;
  }
  // 如果既不是调休工作日也不是节假日，则根据是否为周末判断
  return !fd.weekends;
}


/**
 * 判断给定的日期是否为节假日。
 * 
 * @param {string | number | Date} day - 要判断的日期，可以是日期字符串、时间戳或 Date 对象。
 * @returns {boolean} 如果是节假日返回 true，否则返回 false。
 */
function isHoliday(day: string | number | Date) {
  // 通过调用 isWorkday 函数并取反来判断是否为节假日
  return !isWorkday(day);
}


/**
 * 判断给定的日期是否为调休工作日。
 * 
 * @param {string | number | Date} day - 要判断的日期，可以是日期字符串、时间戳或 Date 对象。
 * @returns {boolean} 如果是调休工作日返回 true，否则返回 false。
 */
function isAddtionalWorkday(day: string | number | Date) {
  // 调用 formatDate 函数格式化输入的日期
  const fd = formatDate(day);
  // 检查该日期是否在调休工作日列表中，使用 !! 将结果转换为布尔值
  return !!WEEKENDS_WORKDAY[fd.date];
}

/**
 * 获取指定日期对应的节日或工作日信息。
 * 
 * @param {string | number | Date} day - 要查询的日期，可以是日期字符串、时间戳或 Date 对象。
 * @returns {string} 返回该日期对应的节日名称，如果是调休工作日则返回调休原因，如果是普通工作日则返回 '工作日'，如果是周末则返回 '周末'。
 */
function getFestival(day: string | number | Date) {
  // 调用 formatDate 函数格式化输入的日期
  const fd = formatDate(day);
  // 检查该日期是否在调休工作日列表中
  if (WEEKENDS_WORKDAY[fd.date]) {
    // 如果在列表中，返回调休工作日对应的原因
    return uni.$u.config.i18n(WEEKENDS_WORKDAY[fd.date]);
  }
  // 检查该日期是否在节假日列表中
  else if (HOLIDAYS[fd.date]) {
    // 如果在列表中，返回该日期对应的节日名称
    return uni.$u.config.i18n(HOLIDAYS[fd.date]);
  }
  // 如果既不是调休工作日也不是节假日，则根据是否为周末返回相应信息
  return fd.weekends ? uni.$u.config.i18n('周末') : uni.$u.config.i18n('工作日');
}


/**
 * 格式化日期，将输入的日期转换为特定格式的日期字符串，并判断是否为周末。
 * 
 * @param {string | number | Date} day - 要格式化的日期，可以是日期字符串、时间戳或 Date 对象。
 * @returns {{ date: string; weekends: boolean }} - 返回一个包含格式化日期字符串和是否为周末的布尔值的对象。
 */
function formatDate(day: string | number | Date) {
  // 创建一个 Date 对象，用于处理输入的日期
  const d = new Date(day);
  // 获取月份，注意月份从 0 开始，所以要加 1
  let month = `${d.getMonth() + 1}`;
  // 获取日期
  let day1 = `${d.getDate()}`;
  // 获取年份
  const year = d.getFullYear();
  // 如果月份是个位数，前面补 0
  if (month.length < 2) {
    month = `0${month}`;
  }
  // 如果日期是个位数，前面补 0
  if (day1.length < 2) {
    day1 = `0${day1}`;
  }

  return {
    // 格式化日期为 YYYY-MM-DD 格式
    date: [year, month, day1].join('-'),
    // 判断是否为周末，0 表示周日，6 表示周六
    weekends: [0, 6].includes(d.getDay()),
  };
}

